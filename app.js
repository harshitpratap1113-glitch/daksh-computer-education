(function () {
  const photos = Array.isArray(window.DAKSH_PHOTOS) ? window.DAKSH_PHOTOS : [];
  const galleryGrid = document.getElementById('galleryGrid');
  const searchInput = document.getElementById('gallerySearch');
  const filterButtons = Array.from(document.querySelectorAll('[data-filter]'));
  const lightbox = document.getElementById('lightbox');
  const lightboxImage = document.getElementById('lightboxImage');
  const lightboxCaption = document.getElementById('lightboxCaption');
  const menuToggle = document.getElementById('menuToggle');
  const navLinks = document.getElementById('navLinks');

  let currentFilter = 'all';
  let activeList = [];
  let currentIndex = 0;

  function getFilteredList() {
    const query = (searchInput ? searchInput.value : '').trim().toLowerCase();
    return photos.filter(item => {
      const matchFilter = currentFilter === 'all' || item.group === currentFilter;
      const fullText = (item.title + ' ' + item.note + ' ' + item.sourceLabel).toLowerCase();
      const matchSearch = !query || fullText.includes(query);
      return matchFilter && matchSearch;
    });
  }

  function showLightbox(idx) {
    if (!activeList.length) return;
    currentIndex = (idx + activeList.length) % activeList.length;
    const item = activeList[currentIndex];
    lightboxImage.src = item.src;
    lightboxImage.alt = item.note || item.title;
    lightboxCaption.textContent = item.title + ' · ' + item.sourceLabel + (item.note ? ' — ' + item.note : '');
    if (!lightbox.open && typeof lightbox.showModal === 'function') {
      lightbox.showModal();
    }
  }

  function renderGallery() {
    activeList = getFilteredList();
    if (!galleryGrid) return;
    galleryGrid.replaceChildren();

    if (!activeList.length) {
      const empty = document.createElement('div');
      empty.className = 'empty-state';
      empty.textContent = 'इस filter/search में कोई photo नहीं मिली।';
      galleryGrid.appendChild(empty);
      return;
    }

    activeList.forEach((item, index) => {
      const card = document.createElement('button');
      card.type = 'button';
      card.className = 'gallery-card';
      card.setAttribute('aria-label', item.title + ': बड़ा देखने के लिए खोलें');

      const img = document.createElement('img');
      img.src = item.src;
      img.alt = item.note || item.title;
      img.loading = 'lazy';
      img.decoding = 'async';

      const body = document.createElement('span');
      body.className = 'gallery-card-body';

      const title = document.createElement('strong');
      title.textContent = item.title;

      const badge = document.createElement('span');
      badge.textContent = item.sourceLabel;

      body.append(title, badge);
      card.append(img, body);
      card.addEventListener('click', () => showLightbox(index));
      galleryGrid.appendChild(card);
    });
  }

  filterButtons.forEach(btn => {
    btn.addEventListener('click', () => {
      currentFilter = btn.dataset.filter || 'all';
      filterButtons.forEach(b => {
        const isSelected = b === btn;
        b.classList.toggle('active', isSelected);
        b.setAttribute('aria-pressed', String(isSelected));
      });
      renderGallery();
    });
  });

  if (searchInput) searchInput.addEventListener('input', renderGallery);
  document.getElementById('lightboxClose')?.addEventListener('click', () => lightbox.close());
  document.getElementById('lightboxPrev')?.addEventListener('click', () => showLightbox(currentIndex - 1));
  document.getElementById('lightboxNext')?.addEventListener('click', () => showLightbox(currentIndex + 1));

  lightbox?.addEventListener('click', (e) => {
    if (e.target === lightbox) lightbox.close();
  });

  lightbox?.addEventListener('keydown', (e) => {
    if (e.key === 'ArrowLeft') showLightbox(currentIndex - 1);
    if (e.key === 'ArrowRight') showLightbox(currentIndex + 1);
  });

  menuToggle?.addEventListener('click', () => {
    const isOpen = navLinks.classList.toggle('open');
    menuToggle.setAttribute('aria-expanded', String(isOpen));
  });

  navLinks?.querySelectorAll('a').forEach(a => {
    a.addEventListener('click', () => {
      navLinks.classList.remove('open');
      menuToggle?.setAttribute('aria-expanded', 'false');
    });
  });

  // Initial render
  renderGallery();
})();
